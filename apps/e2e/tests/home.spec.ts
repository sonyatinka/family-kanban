import { expect, test } from '@playwright/test';
import { createFamily, newUser, signUp, signUpWithFamily } from './helpers';

// Home page: creating a family and the "System status" card

test('1. a user without a family sees the create form and a healthy system status', async ({
  page,
}) => {
  await signUp(page, newUser());

  await expect(page.getByRole('heading', { name: 'Create your family' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create family' })).toBeVisible();

  // The card is the <section> that contains the "System status" heading
  const status = page.locator('section', {
    has: page.getByRole('heading', { name: 'System status' }),
  });
  // An array checks the whole list: exactly these three lines, in this order
  await expect(status.getByRole('listitem')).toHaveText([
    'API: ✅ running',
    'PostgreSQL: ✅',
    'Redis: ✅',
  ]);
});

test('2. an empty family name shows a field error and sends no request', async ({ page }) => {
  await signUp(page, newUser());

  // Remember whether the browser sends POST /api/families at any point from here on
  let posted = false;
  page.on('request', (request) => {
    if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/families') {
      posted = true;
    }
  });

  await page.getByRole('button', { name: 'Create family' }).click();

  const nameInput = page.getByLabel('Family name');
  await expect(page.getByText('Enter a family name')).toBeVisible();
  // The error belongs to this field: Field.tsx links them with aria-describedby
  await expect(nameInput).toHaveAccessibleDescription('Enter a family name');
  await expect(nameInput).toHaveAttribute('aria-invalid', 'true');
  // The form validates before sending, so by the time the error is on screen a request
  // would have been made already
  expect(posted).toBe(false);
  await expect(page).toHaveURL('/');
});

test('3. creating a family opens its page', async ({ page }) => {
  await signUp(page, newUser());

  await page.getByLabel('Family name').fill('The Testers');
  await page.getByRole('button', { name: 'Create family' }).click();

  // The id is a UUID generated by the database
  await expect(page).toHaveURL(/\/families\/[0-9a-f-]{36}$/);
  await expect(page.getByRole('heading', { name: 'The Testers' })).toBeVisible();
});

test('4. the home page lists the new family with the role instead of the form', async ({
  page,
}) => {
  await signUp(page, newUser());
  const familyPath = await createFamily(page, 'The Testers');

  await page.getByRole('link', { name: '← Home' }).click();

  await expect(page).toHaveURL('/');
  await expect(page.getByRole('heading', { name: 'Your families' })).toBeVisible();
  // One row: a link to the family page and the role badge
  const row = page.getByRole('listitem').filter({ hasText: 'The Testers' });
  await expect(row.getByRole('link', { name: 'The Testers' })).toHaveAttribute('href', familyPath);
  await expect(row.getByText('Parent', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Create your family' })).toBeHidden();
  await expect(page.getByRole('button', { name: 'Create family' })).toBeHidden();
});

test('13. the status card shows "Checking…" again when the home page is reopened', async ({
  page,
}) => {
  await signUpWithFamily(page, 'The Testers');
  await page.getByRole('link', { name: '← Home' }).click();
  // The first check is finished, and its answer is in the query cache
  await expect(page.getByText('API: ✅ running')).toBeVisible();
  await page.getByRole('link', { name: 'The Testers' }).click();
  await expect(page.getByRole('heading', { name: 'Members' })).toBeVisible();

  // From now on hold every health answer for a second. The real check takes a few
  // milliseconds, too short to see "Checking…" reliably.
  await page.route('**/api/health', async (route) => {
    await new Promise((resolve) => setTimeout(resolve, 1000));
    await route.continue();
  });
  await page.getByRole('link', { name: '← Home' }).click();

  // While the new check is running, the cached answer of the previous one must not show
  await expect(page.getByText('Checking…')).toBeVisible();
  await expect(page.getByText('API: ✅ running')).toBeHidden();
  // Then the fresh answer replaces "Checking…"
  await expect(page.getByText('API: ✅ running')).toBeVisible();
  await expect(page.getByText('Checking…')).toBeHidden();
});
